// Коды ошибок шлюза -> понятный клиенту текст.
// Сырые ответы банка не показываем: они непонятны, а некоторые ("карта
// украдена") нельзя раскрывать — это подсказка мошеннику. Такие коды
// шлюз заранее превращает в общий card_declined.
const MESSAGES: Record<string, string> = {
  card_declined: "Банк отклонил платёж. Попробуйте другую карту или обратитесь в банк.",
  insufficient_funds: "Недостаточно средств на карте.",
  invalid_card: "Проверьте данные карты.",
  invalid_token: "Данные карты устарели — введите их ещё раз.",
  authentication_failed: "Не удалось подтвердить платёж кодом из SMS (3-D Secure).",
  authentication_canceled: "Подтверждение платежа отменено.",
  wallet_declined: "Платёж отклонён в кошельке.",
  acquirer_unavailable: "Банк временно недоступен. Попробуйте ещё раз через минуту.",
  payment_expired: "Время на оплату истекло. Попросите продавца выставить счёт заново.",
  payment_already_succeeded: "Этот счёт уже оплачен.",
  network_error: "Нет соединения. Проверьте интернет — деньги не списаны, пока вы не увидите успех.",
  timeout: "Сервер долго не отвечает. Проверьте статус перед повторной оплатой.",
};

const FALLBACK = "Не удалось провести платёж. Попробуйте ещё раз или выберите другой способ оплаты.";

export function getErrorMessage(code: string | null | undefined): string {
  return (code && MESSAGES[code]) || FALLBACK;
}
